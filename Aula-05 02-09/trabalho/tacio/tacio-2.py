#2 - Crie um programa que multiplique 2 números float e mostre na tela

#Funçao main
def main():
    print("--------------------------------")
    print("--Mutiplicação de dois numeros--")
    print("--------------------------------\n")

    #entrada de dados
    a = float(input("Digite o valor de A: "))
    b = float(input("Digite o valor de B: "))

    #saida de dados
    print("Resultado:", a*b)


#chamando a Main
main()